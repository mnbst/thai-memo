# 説明ではなく毎回違う値が入ること。台帳の「温度・多様性はプロンプトで解決しない」。
#
# 抽選だけを足すと訳文に関係が漏れる（「先輩、これ一緒に食べませんか」が 1件→7件）。
# _RELATION_NO_LEAK_LINE で 1件に戻る。この1行の代償は文末詞の種類が 8→4 に減ること。
