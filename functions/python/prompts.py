# 2026-08-22 実測。現行は話者が ผม 一人に固定されていた（120文中 ผม 25〜29 に対し
# 他の人称は各1〜5）。関係をサーバーで抽選して末尾に渡すと人称・文末詞が分岐する。
#
#                        a1     a2     抽選    抽選+訳漏れ対策（採用）
#   人称ユニーク数         7      5      10     7
