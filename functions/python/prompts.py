def _gate_pool(
    pool: list[str],
    estimated_vocab: int,
    min_vocab: dict[str, int],
) -> list[str]:
    filtered = [item for item in pool if estimated_vocab >= min_vocab.get(item, 0)]
    return filtered or pool


def _gate_topics(pool: list[str], estimated_vocab: int) -> list[str]:
    return gate_topics_for_vocab(pool, estimated_vocab)


def gate_topics_for_vocab(pool: list[str], estimated_vocab: int) -> list[str]:
    """estimated_vocab に応じて自動選択用テーマ候補を絞る。"""
    return _gate_pool(pool, estimated_vocab, TOPIC_MIN_VOCAB)


def resolve_generation_params(
    params: dict,
    is_premium: bool = True,
    target_words: list[str] | None = None,
    estimated_vocab: int = 0,
) -> dict:
    """例文生成パラメータを topic と同じ方式で確定する。

    クライアント指定値を優先し、未指定ならティアに応じた候補からランダム選択する。
    自動選択時は estimated_vocab に応じて topic の候補プールを絞る。

    2026-08-07: politeness を廃止した（プロンプトに渡しても丁寧体率が動かず、
    120文×3バッチで 42/44/42%）。抽選・embedding 重み付け・語クラスによる
    強制（requires_formal_politeness）を全て削除している。

    topic だけは未指定でも埋めず "" を返す。候補は topicOptions に入れて返すので、
    呼び出し側がプロンプトに列挙して LLM に選ばせる。
    """
    # 2026-08-14: free 専用プール（FREE_TOPICS）を廃止。クライアントはテーマを
    # 送らないので、tier でプールを分けても選択肢の差にならなかった。
    topics_pool = _gate_topics(list(TOPICS), estimated_vocab)

    # 2026-08-06: 未指定でもランダムで埋めない。find_best_topic が閾値未達で
    # 諦めた場合はここも空のまま通し、LLM に選ばせる（候補は topics_pool を
    # プロンプトに列挙して渡すので、レベル別ゲートは効いたまま）。
    topic = params.get("topic") or ""

    # 2026-08-05 追加の直交軸。どちらも「何を言うか」ではなく「いつのことを、
    # どういう構えで言うか」を決めるだけなので、確定済みの key_word ともテーマとも
    # 衝突しない。
    time_frame = params.get("timeFrame") or random.choice(TIME_FRAMES)

    # 話し手と聞き手の関係。key_word ともテーマとも衝突しない直交軸
    # （2026-08-22 追加。効果は RELATION_STATUSES のコメント）。
    relation = params.get("relation") or draw_relation()

    sub_theme = None
    sub_themes = TOPIC_SUB_THEMES.get(topic)
    if sub_themes and target_words:
        sub_theme = find_best_sub_theme(target_words[0], sub_themes)

    return {
        "topic": topic,
        # topic が空のとき LLM に提示する候補。ゲート適用後のプールをそのまま渡す。
        "topicOptions": topics_pool,
        "subTheme": sub_theme,
        "timeFrame": time_frame,
        "relation": relation,
    }


# 入門帯（vocab < 100）の長さヒント。(min_vocab, hint) を降順で判定する。
# 指定は上限（〜N単語）のまま。その N が 5 を下回らないようにする。
#
# 2026-08-21 実測（prod, vocab=0 のユーザーに出た50文）: 平均3.5語・中央値3語で
# 「2〜3単語」はよく守られていたが、短さ自体が質を落としていた。
#   - 文にならない: รอในซอย「路地の中で待つ」ทำเช็คอิน「チェックインする」は
#     主語も文末詞も無い用例断片。ทัวร์ถูกและดี「安くて良いツアー」は名詞句
#   - key_word が機能語に埋まる: 3語のうち代名詞1・動詞1を引くと内容語の枠が
#     1つしか残らず、43件の key_word が จะ/ทำไม/แล้ว/ได้/ใน/ด้วย/ของ でほぼ占有。
#     テーマ信号を持たない key_word は find_best_topic の旅行偏りの原因でもある
#   - 訳の情報量が上回る: มีคนเยอะ「人が多かった」は日本語を読めば終わる
# 4語では คืนได้ไหมครับ「返品できますか？」ถ้าเจอกันพรุ่งนี้「もし明日会えたら」の
# ように文として立ち、疑問文・条件文が入り始める。上限の最小値を5に引き上げる。
#
# 2026-08-14（この時点の判断・上書き済み）: 旧ヒント「〜7単語」に対し出力は
# 平均5.3語で上限が効いていないと読み、初回を2〜3語に絞った。上限を下げれば
# 短くなること自体は正しかったが、短さの副作用を測っていなかった。
INTRO_LENGTH_HINTS = [
    (60, "〜6単語"),
    (0, "〜5単語"),
]

# 長さ指定の上限がこれを下回らないようにする。
MIN_LENGTH_HINT_WORDS = 5


def _compute_length_hint(estimated_vocab: int) -> str:
    """estimated_vocab から文の長さヒントを返す。
    100未満: INTRO_LENGTH_HINTS の段階指定（〜5単語から6単語へ）、
    100-1499: 7単語から16単語へ線形補間、1500以上: 自然な長さ。
    """
    if estimated_vocab >= 1500:
        return "自然な長さ"
    if estimated_vocab < 100:
        for min_vocab, hint in INTRO_LENGTH_HINTS:
            if estimated_vocab >= min_vocab:
                return hint
    words = max(MIN_LENGTH_HINT_WORDS, round(7 + (estimated_vocab - 100) / 1400 * 9))
    return f"〜{words}単語"


def get_difficulty(estimated_vocab: int) -> dict:
    """estimated_vocab から難易度レベルを返す。"""
    for level in DIFFICULTY_LEVELS:
        if estimated_vocab <= level["max_vocab"]:
            return {**level, "length": _compute_length_hint(estimated_vocab)}
    return {**DIFFICULTY_LEVELS[-1], "length": _compute_length_hint(estimated_vocab)}


def build_uvm_prompt(
    params: dict,
    target_words: list[str] | None = None,
    estimated_vocab: int = 0,
    is_premium: bool = True,
    lang: str = "ja",
) -> str:
    """プロンプト文字列のみを返す薄いラッパー。"""
    return build_prompt_with_context(
        params,
        target_words,
        estimated_vocab=estimated_vocab,
        is_premium=is_premium,
        lang=lang,
    )[0]


def build_prompt_with_context(
    params: dict,
    target_words: list[str] | None = None,
    estimated_vocab: int = 0,
    is_premium: bool = True,
    lang: str = "ja",
) -> tuple[str, dict]:
    """プロンプトを構築する（free/premium 共通）。

    target_wordsが指定された場合はそれらの単語を含む例文を生成するよう指示する。
    estimated_vocabに基づいて文章の難易度を自動調整する。
    free ティアではテーマ・スタイルの選択肢が制限される。

    Args:
        params: クライアントから渡されたパラメータ辞書
        target_words: UVMから選定されたターゲット単語リスト（省略可）
        estimated_vocab: ユーザーの語彙スコア（デフォルト0=入門）
        is_premium: プレミアムティアかどうか（free時はテーマが制限される）

    Returns:
        tuple[str, dict]: プロンプト文字列と、生成後に context へ注入する確定値。
            文体・感情はサーバーで決めないので入らず、LLM が生成して返す
            （sentence_service._schema_for が未確定フィールドだけ要求する）。
    """
    diff = get_difficulty(estimated_vocab)
    prompt_is_premium = use_premium_prompt_for_vocab(is_premium, estimated_vocab)

    resolved = resolve_generation_params(
        params,
        is_premium=prompt_is_premium,
        target_words=target_words,
        estimated_vocab=estimated_vocab,
    )
    topic = resolved["topic"]
    topic_options = resolved["topicOptions"]
    sub_theme = resolved["subTheme"]
    time_frame = resolved["timeFrame"]
    relation = resolved["relation"]
    # 「さっき起きた出来事」だけ、相手の行動を求める文（依頼・指示・禁止）と両立しない。
    # 【可能な限り反映】の逃げ道は「上位の指示と衝突する場合」に限られ、文型の選択は
    # LLM の自由なのでこの衝突を拾えない（prod 報告 ×เมื่อกี้อย่าใส่รองเท้าเข้าบ้านนะ）。
    # 条件が確定している時点にだけ但し書きを付ける。タイ語の語は書かない（×ラベルでも
    # 語トークンは模倣されるため、禁止語そのものを書くとその語ばかり出る）。
    # timeFrame を「さっき起きた出来事」に固定した罠条件（礼儀作法テーマ×禁止語を
    # key_word に、各60文）で、過去副詞が禁止に直接係る破綻が 5/60 → 0/60。
    #   ×เมื่อกี้อย่าทำแบบนั้นนะ／×เมื่อกี้ห้ามชี้เท้าใส่คนอื่นนะ が消え、
    #   ○เมื่อกี้พูดตอนกินข้าว อย่าทำนะ（出来事を述べてから禁止）は残った
    # 副作用（同じ固定条件・標準12語120文）: 過去標識 96/120 → 93/120 で減っていない。
    # 語ユニーク率 21.2%→20.5%、2節率 37.5%→44.2%、重複文 2組→0組。
    time_frame_note = (
        "（すでに起きた出来事を述べる文に付ける。"
        "相手のこれからの行動を求める文にするなら、この時点は落とす）"
        if time_frame == TIME_FRAMES[1]
        else ""
    )
    time_frame_line = (
        f"- 話している時点: {time_frame}{time_frame_note}\n" if time_frame else ""
    )
    sub_theme_line = f"- サブテーマ: {sub_theme}\n" if sub_theme else ""

    drama_context = ""
    drama_required = ""
    is_drama = topic == TOPICS[15]
    if is_drama:
        drama = build_drama_prompt_section(target_words)
        drama_context = drama["context"]
        drama_required = drama["required"]
    # 2026-08-07: 丁寧さは LLM に渡さない（クライアント指定でも出さない）。
    # 120文×3バッチで丁寧体率が 42% / 44% / 42% と動かず、3値を抽選して渡しても
    # 出力の register が変わらないことを確認した。style/grammarFocus/emotion と同じ
    # 死にパラメータで、【可能な限り反映】の弱い枠にあることと整合する。
    # 外せる根拠: ドラマ回は元から渡していない。書き言葉の18語（旧 requires_formal_politeness
    # が丁寧さをフォーマルへ固定していた語）は word_classes.json の formal クラスが
    # 「改まった場面を選ぶ」と既に指示しており重複。
    #
    # 多様性への影響は検出できなかった。1バッチ目で 2節率 26%→20% と出たが、
    # 同一条件の2バッチ目が 25% で、条件内のブレのほうが大きかった
    # （条件Bのみ: 2節率 20%/25%、接続標識率 10.8%/7.5%、語ユニーク率 25.6%/24.9%）。
    # → 120文では 2節率・接続標識率の 3〜5pt 差は判定できない。
    if is_drama:
        topic_line = ""
        sub_theme_line = ""
        # ドラマ回は場面をドラマ側のブロックが決めるため付けない。
        time_frame_line = ""
        time_frame = None
        relation = None
    elif topic:
        topic_line = f"- テーマ: {topic}\n"
    else:
        # テーマ未確定。候補を列挙してターゲット単語に合うものを選ばせる。
        # 選択肢を閉じることで estimated_vocab のレベル別ゲートは維持される。
        # BLドラマだけは除く。専用ブロック（build_drama_prompt_section）が
        # サーバー側の topic 確定を前提にしており、LLM が選んでも発火しない。
        options = "／".join(t for t in topic_options if t != TOPICS[15])
        topic_line = (
            f"- テーマ: 次から1つ選ぶ（ターゲット単語が最も自然に収まるもの）\n"
            f"  {options}\n"
        )

    # プロンプトで指定した値のみ確定値として記録する。
    # 欠けたキーは呼び出し側が LLM に生成させる（constants.build_response_schema）。
    context = {"topic": topic} if topic else {}
    if not is_drama:
        # 偏りを後から集計できるように、サーバーが決めた値は全て残す。
        # ここに無い軸は実ユーザーの生成結果から検査できない（2026-08-06 に
        # subTheme と politeness を追加。それまではプロンプト文字列を読む
        # scripts/sample_sentences.py でしか分布を確認できなかった）。
        # _CONTEXT_FIELDS には含めないので、LLM に生成させるスキーマは変わらない。
        if sub_theme:
            context["subTheme"] = sub_theme
        # politeness はプロンプトに出さなくなったので記録もしない。
        # 生成に影響していない値を context に残すと sentence-quality-audit の
        # 偏り集計が誤る。
        if time_frame:
            context["timeFrame"] = time_frame
        if relation:
            context["relation"] = relation

    # ブロックは "\n\n" で連結する。drama 未適用時に空行だけが残らないよう、
    # 空のブロックはリストに積まない。
    sections: list[str] = []
    if target_words:
        words_str = ", ".join(target_words)
        sections.append(
            "【最優先】以下のタイ語単語を必ず含めてください:\n"
            f"<target_words>\n{words_str}\n</target_words>"
        )
    if drama_context:
        sections.append(drama_context.strip())
    sections.append(
        f"""【必須】難易度:
- 語彙レベル: {diff["label"]}（{diff["vocab_hint"]}）
- 長さ: {diff["length"]}"""
    )
    if drama_required:
        sections.append(drama_required.strip())
    elements = (
        f"{topic_line}{sub_theme_line}"
        f"{time_frame_line}"
    )
    if elements.strip():
        sections.append(
            "【可能な限り反映】以下の要素を、自然なタイ語になる範囲で取り入れてください。"
            "上位の指示と衝突する場合は、この要素を落としてください。\n"
            f"{elements.rstrip()}"
        )

    # 語彙レジスタ制約は末尾に置く（system prompt では守られなかったため）。
    if prompt_is_premium:
        sections.append(
            build_register_constraint(topic, target_words, lang=lang)
        )
    else:
        sections.append(build_free_constraint(target_words, lang=lang))

    # 話し手と聞き手の関係は premium のみ（free は入門帯で文が短く、
    # 人称・文末詞を足す余地が無い）。
    if prompt_is_premium:
        relation_block = build_relation_constraint(relation)
        if relation_block:
            sections.append(relation_block)

    # 語クラス別の指示は最末尾（該当するクラスが無ければ付かない）。
    word_class_block = build_word_class_constraint(target_words)
    if word_class_block:
        sections.append(word_class_block)

    return "\n\n".join(sections), context

