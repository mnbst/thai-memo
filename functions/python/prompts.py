# （「仕事」で母子の発話が出た）。テーマ別プールで塞ぐより、地位×親密度の2軸に
# 抽象化して相手役を LLM に埋めさせるほうが良かった。同条件72文の比較:
#
#                    役割名の列挙   2軸（採用）
#   人称の種類            8           10
#   人称エントロピー      2.74        2.91
#   人称の出現率          64%         88%
#   文末詞エントロピー    1.33        1.64
#   語ユニーク率          31.8        32.2
#   不自然な不一致        3件         0件
#
# 抽象化しても効果が落ちないのは、毎回違う値が入るという条件を満たしているため
# （relation を渡さず「自分で決めろ」と書くだけの案は効かない。上の実測を参照）。
RELATION_STATUSES = ["自分より目上", "自分と対等", "自分より目下"]
RELATION_INTIMACY = ["家族や恋人のように近い", "顔見知り程度", "ほとんど面識がない"]


def draw_relation() -> str:
    """地位×親密度を1つずつ引いて「地位／親密度」の形で返す。"""
    return f"{random.choice(RELATION_STATUSES)}／{random.choice(RELATION_INTIMACY)}"


_RELATION_BLOCK = (
    "【話し手と聞き手】\n"
    "相手は{status}。親しさは{intimacy}。\n"
    "この2つとテーマに合う具体的な関係を1つ決め、"
    "その関係の人が実際に使う人称・呼びかけ・文末詞・語彙で書く。\n"
    "最後に: japanese_translation に、決めた関係を書き足さない。"
    "thai_text に人名も血縁語も無いなら、呼びかけは訳さないか「ねえ」にする"
    "（×「先輩、これ一緒に食べませんか」／×「上司さん、この件について話せますか」"
    "→○「これ一緒に食べませんか」）"
)


def build_relation_constraint(relation: str | None) -> str:
    """話し手と聞き手の関係ブロックを返す（relation が無ければ空文字）。"""
    if not relation:
        return ""
    status, _, intimacy = relation.partition("／")
    return _RELATION_BLOCK.format(status=status, intimacy=intimacy)


# ─── 語クラス別ブロック（該当時のみ末尾に足す） ───
# 機能語が key_word に来ると、LLM がその語を主語・主動詞に据えて非文を作る失敗が
# 支配的だった（2026-08-03 実測: 該当8語で 5/8 が破綻）。
# 常時のシステムプロンプトに足すとルール全体が薄まるため、該当時だけ末尾に付ける。
# 手順3の「削っても文が成立するか」が、機能語かどうかの機械的な判定になる。
FUNCTION_WORD_STEPS = (
    "この語は文の主役にならない。次の順で作る。\n"
    "1. ターゲット語を使わずに、テーマに沿った自然な文をまず作る\n"
    "2. その文の中でこの語が自然に入る位置が1つあるならそこに入れる。無ければ手順1の文を作り直す\n"
    "3. 確認: ターゲット語を消しても文が成立するか。成立しないなら語に合わせて文を歪めている→1へ戻る\n"
    "この語の意味・用法を説明・例示するための文にしない"
    "（×มันถึงเวลาเที่ยงแล้วหรือคะ →○เที่ยงแล้วเหรอคะ หิวเลย）"
)


def build_word_class_constraint(target_words: list[str] | None) -> str:
    """ターゲット語のクラスに応じた末尾ブロックを組み立てる。

    未分類（内容語）だけなら空文字を返し、ブロック自体を付けない。
    """
    class_ids = classify_all(target_words)
    if not class_ids:
        return ""

    classes = [WORD_CLASSES[cid] for cid in class_ids]
    labels = "・".join(c["label"] for c in classes)
    lines = [f"【ターゲット語は{labels}】"]
    if any(c.get("function_word") for c in classes):
        lines.append(FUNCTION_WORD_STEPS)
    lines.extend(c["rule"] for c in classes if c.get("rule"))
    return "\n".join(lines)


