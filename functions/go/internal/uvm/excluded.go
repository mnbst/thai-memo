package uvm

// key_word から外す語。
//
// 単独では古語・方言・専門用語の用法しか無い語が key_word に当たると、
// 【最優先】ターゲット語必須がその1文を丸ごと壊す。プロンプト側には
// 「文語・古語の用法しかないなら文脈ごと変える」ルールがあるが、
// 語自体が古語専用なら文脈を変えても逃げ場が無いので出題側で外す。
//
// 旧実装（functions/python の build_non_vocab_dict.py + non_vocab.py）は
// Go へ未移植のまま消えた。ここはその代替で、実測で破綻した語だけを持つ。
// 予防的に語を足さないこと（台帳「予防的ルール」）。
// 例外は「身体・性的接触語」群だけで、あれは破綻率ではなく内容リスクで
// 外している（その群のコメント参照）。
//
// 複合語（เจ้าของ / เจ้านาย）は別トークンなので出題は残る。
var excludedTargetWords = map[string]bool{
	// 2026-08-26: ×เจ้าฝนตกแล้ว。古語・方言の二人称／「主」。
	"เจ้า": true,
	// 2026-08-26: 古語の一人称。เจ้า と同じ理由。
	"ข้า": true,
	// 2026-09-06: ×เตะเข้าเป้าดังวาเลย。長さの単位（約2m）で、
	// 会話文では単独で使いようがなく擬音として捏造された。
	"วา": true,

	// ─── 2026-09-11: 多義・同音で用法を取り違える語 ───
	//
	// 短い語ほど別語と衝突し、モデルが用法を作る。長さでは切れない
	// （จี と同じ2文字に ไป rank7 / มี rank17 / ดี rank42 がある）ので語で持つ。

	// ×ที่นั่นสวยจีๆนะครับ（非文。จี にこの用法は無い）
	// ×คนนั้นเข้ามาจีที่ร้านกาแฟ「口説いてきた」（それは จีบ rank2712。別語）
	// prod 2026-09-09 に2件、どちらも別々の誤用をした。
	"จี": true,
	// ×กำแพงนี้มีรูไปส่องดูกันไหม「壁に穴があるけど覗きに行かない？」
	// 「穴」単独は会話文で性的な含みに落ちやすい。prod 2026-09-09。
	"รู": true,
	// ×พรุ่งนี้จะไปดูหนังกับแก → 訳「明日は彼と映画を見に行く」
	// แก は二人称。訳が三人称に化けた。แก่（老）・แกง とも衝突する。
	// prod 2026-09-09。
	"แก": true,

	// ─── 2026-09-11: 身体・性的接触語 ───
	//
	// ここだけは破綻率ではなく内容リスクで外す（＝実測で壊れていなくても
	// 足してよい唯一の群）。BL・恋愛テーマと組むと、文法的に正しいまま
	// 審査に出せない文になる。テーマ自体は訴求の柱なので、日常語として
	// 使い道のある語（จูบ กอด ปาก ขา นม）は外さない。
	//
	// 発端: ×พี่แกงอย่าทำตัวน่ากิน กูอยากเลิกเรียนมาเลียปากพี่
	//       「学校を抜けて先輩の唇を舐めたくなっちゃうだろ」prod 2026-09-09。
	"เลีย":   true,
	"ลิ้น":   true,
	"หน้าอก": true,
	"เปลือย": true,
	"อึ๊บ":   true,
	"เย็ด":   true,

	// ─── 2026-09-11: 世界観を引きずる語 ───
	//
	// テーマに無い設定を1語が持ち込み、その日の生成がまとめて寄る。
	// ×โรงแรมนี้ไม่มีมนุษย์พักอยู่เลย「ホテルに人間が全く泊まっていない」
	//   （宿泊客に มนุษย์ は使わない。คน）prod 2026-09-09。
	// ผี は 2026-09-10 に4件（趣味・BLテーマなのに幽霊。前日・翌日は0件）。
	// 同じ機序の語を併せて外す。เทพ・นางฟ้า は褒め言葉の口語用法があるので残す。
	"มนุษย์":       true,
	"ผี":           true,
	"วิญญาณ":       true,
	"ปีศาจ":        true,
	"ซอมบี้":       true,
	"สัตว์ประหลาด": true,
	"มังกร":        true,
	"เวทมนตร์":     true,
}

// IsExcludedTargetWord は key_word にしてはいけない語かを返す。
func IsExcludedTargetWord(word string) bool {
	return excludedTargetWords[word]
}
