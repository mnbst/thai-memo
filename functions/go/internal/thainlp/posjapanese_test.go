package thainlp

import "testing"

func TestTagWordsContext(t *testing.T) {
	cases := []struct {
		name  string
		words []string
		index int
		want  string
	}{
		{"ของ 持ち主", []string{"หนังสือ", "ของ", "ฉัน"}, 1, "前置詞"},
		{"ของ 動詞の後でも代名詞なら持ち主", []string{"เดินทาง", "ของ", "ฉัน"}, 1, "前置詞"},
		{"ของ 動詞の目的語", []string{"ซื้อ", "ของ"}, 1, "名詞"},
		{"ของ 類別詞の前", []string{"ของ", "ชิ้น", "นี้"}, 0, "名詞"},
		{"ของ 関係節の前", []string{"ราคา", "ของ", "ที่", "ซื้อ"}, 1, "名詞"},
		{"ที่ 場所", []string{"วาง", "ที่", "โต๊ะ"}, 1, "前置詞"},
		{"ที่ 関係節", []string{"ร้าน", "ที่", "คน", "แนะนำ"}, 1, "代名詞"},
		{"ที่ 動詞の前", []string{"คน", "ที่", "มา"}, 1, "代名詞"},
		{"ที่ ตาม の後", []string{"ตาม", "ที่", "พี่"}, 1, "代名詞"},
		{"ที่ ตอน の後", []string{"ตอน", "ที่", "แมว", "อ้อน"}, 1, "代名詞"},
		{"ที่ ทุกครั้ง の後", []string{"ทุกครั้ง", "ที่", "การบ้าน"}, 1, "代名詞"},
		{"ที่ ก่อน の後は節", []string{"คุย", "กัน", "ก่อน", "ที่", "จุดจบ", "จะ", "มา", "ถึง"}, 3, "代名詞"},
		{"ขึ้น 形容詞の後", []string{"ดี", "ขึ้น"}, 1, "助動詞"},
		{"ไป 本動詞", []string{"จะ", "ไป"}, 1, "動詞"},
		{"ไป 動詞の後", []string{"หาย", "ไป"}, 1, "助動詞"},
		{"ใบ 名詞＋指示語の前は類別詞", []string{"ถัง", "ใบ", "นี้"}, 1, "類別詞"},
		{"คน 名詞＋指示語の前は類別詞", []string{"นักร้อง", "คน", "นี้"}, 1, "類別詞"},
		{"ตัว 数詞の後は類別詞", []string{"เสื้อ", "สอง", "ตัว"}, 2, "類別詞"},
		{"คน 文頭は名詞のまま", []string{"คน", "นี้", "ใจดี"}, 0, "名詞"},
		{"คน 指示語が無ければ名詞のまま", []string{"กฎ", "บอกว่า", "คน", "แพ้"}, 2, "名詞"},
		{"หลัง 数詞の後でも〜の後で", []string{"ชั้น", "สาม", "หลัง", "เลิก", "เรียน"}, 2, "接続詞"},
		{"หลัง 名詞＋指示語の前は類別詞", []string{"บ้าน", "หลัง", "นี้"}, 1, "類別詞"},
		{"ฉัน 僧侶の食事の前は動詞", []string{"หลวงพ่อ", "ฉัน", "เพล"}, 1, "動詞"},
		{"เพล ฉัน の後は名詞", []string{"หลวงพ่อ", "ฉัน", "เพล"}, 2, "名詞"},
		{"ฉัน ふつうは代名詞", []string{"ฉัน", "ชอบ", "กิน", "ข้าว"}, 0, "代名詞"},
		{"ทัวร์ は名詞", []string{"จอง", "ทัวร์"}, 1, "名詞"},
		{"เหนือกว่า は動詞", []string{"นาย", "เหนือกว่า", "ฉัน"}, 1, "動詞"},
		{"หก こぼれる", []string{"ทำ", "น้ำ", "หก", "ใส่", "ผ้า"}, 2, "動詞"},
		{"หก 単位の前は数詞", []string{"ตื่น", "หก", "โมง"}, 1, "数詞"},
		{"หก 番号", []string{"ข้อ", "หก"}, 1, "数詞"},
		{"คืน 返す", []string{"เอา", "หนังสือ", "มา", "คืน"}, 3, "動詞"},
		{"คืน ทั้ง の後は夜", []string{"ฝน", "ตก", "ทั้ง", "คืน"}, 3, "名詞"},
		{"คืน 指示語の前は夜", []string{"คืน", "นั้น", "หนาว"}, 0, "名詞"},
		{"แบบนี้ 名詞の後は限定詞", []string{"งานเลี้ยง", "แบบนี้"}, 1, "限定詞"},
		{"แบบนี้ 動詞の後は副詞", []string{"เล่น", "แบบนี้"}, 1, "副詞"},
		{"ช่าง 動詞の前は職人", []string{"ช่าง", "ก่อ", "ผนัง"}, 0, "名詞"},
		{"ช่าง 形容詞の前はなんて", []string{"ช่าง", "สวย", "จริงๆ"}, 0, "副詞"},
		{"ช่าง ช่างมัน は動詞", []string{"ช่าง", "มัน", "เถอะ"}, 0, "動詞"},
		{"ให้ 受益", []string{"ค้นหา", "ข้อมูล", "ให้", "ผม", "หน่อย"}, 2, "前置詞"},
		{"ให้ 文末の受益", []string{"ทำ", "ทุกอย่าง", "ให้", "มึง"}, 2, "前置詞"},
		{"ให้ 使役は接続詞のまま", []string{"สอน", "ให้", "เรา", "รู้จัก", "ปล่อยวาง"}, 1, "接続詞"},
		{"ถึง 譲歩", []string{"ถึง", "คุณ", "จะ", "ไม่", "แตะต้อง", "แต่", "มัน", "ก็", "ผิด"}, 0, "接続詞"},
		{"ก่อน 節の終わりは副詞", []string{"เข้าไป", "ที่", "หน้า", "ก่อน"}, 3, "副詞"},
		{"ก่อน 名詞の前は前置詞", []string{"เสร็จ", "ก่อน", "กำหนด"}, 1, "前置詞"},
		{"กำหนด ก่อน の後は名詞", []string{"เสร็จ", "ก่อน", "กำหนด"}, 2, "名詞"},
		{"ก่อน 動詞の前は接続詞", []string{"มืด", "ก่อน", "ถึง", "ที่พัก"}, 1, "接続詞"},
		{"รอบ 指示語の前は名詞", []string{"รอบ", "นี้", "ได้", "โบนัส"}, 0, "名詞"},
		{"ได้ 名詞の前は得る", []string{"รอบ", "นี้", "ได้", "โบนัส"}, 2, "動詞"},
		{"ได้ 動詞の後は助動詞のまま", []string{"ทำ", "ได้"}, 1, "助動詞"},
		{"ทุกเย็น は名詞", []string{"กิน", "ทุกเย็น"}, 1, "名詞"},
		{"แววตา は名詞", []string{"ด้วย", "แววตา"}, 1, "名詞"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got, err := TagWords(c.words)
			if err != nil {
				t.Fatal(err)
			}
			if got[c.index] != c.want {
				t.Errorf("%v[%d] = %q, want %q", c.words, c.index, got[c.index], c.want)
			}
		})
	}
}
