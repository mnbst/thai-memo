// =============================================================================
// generation_constants.dart
// Gemini AIによるタイ語例文生成時に使用するパラメータの選択肢を定義する定数クラス。
//
// ユーザーは例文生成時にスタイル（口語体・丁寧語など）、テーマ（あいさつ・食べ物など）、
// 文法フォーカス、感情などのパラメータを選択できる。これらの選択肢がCloud Functionに
// 送信され、Gemini AIへのプロンプトに組み込まれることで、ユーザーの学習ニーズに
// 合った例文が生成される。
//
// 無料ティアとプレミアムティアで使用可能なパラメータ・選択肢が異なり、
// 無料ユーザーはテーマとスタイルの一部のみ選択可能。プレミアムユーザーは
// 全パラメータ・全選択肢にアクセスでき、さらに自由入力プロンプトも使用可能。
// =============================================================================

import 'dart:math';

/// 例文生成パラメータの選択肢を定義する定数クラス。
///
/// 各パラメータ（スタイル、テーマ、丁寧さ等）の選択肢リストと、
/// 無料/プレミアムティアでの利用可能範囲を管理する。
class GenerationConstants {
  /// インスタンス化を禁止するプライベートコンストラクタ
  GenerationConstants._();

  // ---------------------------------------------------------------------------
  // 例文スタイル（文体）の選択肢
  // ---------------------------------------------------------------------------

  /// 例文の文体スタイル一覧。
  /// 生成される例文がどのような文体で書かれるかを指定する。
  static const styles = [
    'ニュース記事体（客観的・フォーマルな報道文体）',
    '口語体（友達同士のカジュアルな話し言葉）',
    '丁寧語（フォーマルな敬語・丁寧な表現）',
    'SNS・テキストメッセージ（略語・絵文字・短い表現）',
    '物語・文学体（描写的・書き言葉的な表現）',
  ];

  // ---------------------------------------------------------------------------
  // テーマ（話題）の選択肢
  // ---------------------------------------------------------------------------

  /// 例文のテーマ一覧。
  /// どのような場面・話題の例文を生成するかを指定する。
  /// タイの文化・宗教・恋愛など、タイ語学習に実用的なテーマを網羅している。
  static const topics = [
    'タイBLドラマ（告白、すれ違い、再会、嫉妬、裏切り、仲直り、壁ドン、あだ名呼び）',
    '恋愛・男女関係（告白、デート、甘い言葉、遠距離、別れ、仲直り）',
    '仕事（報告・連絡・相談、打ち合わせ、残業申請、同僚雑談）',
    'あいさつ（朝・昼・夜、初対面、再会、別れ、電話）',
    '食べ物（注文、感想、屋台、辛さ調整、アレルギー）',
    '旅行（ホテル、道案内、観光地、空港、ツアー）',
    '家族（家族紹介、子育て、親への感謝、兄弟、家族行事）',
    '買い物（値段交渉、サイズ・色の確認、返品、ナイトマーケット）',
    '交通（Grab、BTS、バイタク、ソンテウ、渋滞）',
    '健康（症状説明、薬局、マッサージ、健康診断）',
    '天気（暑さ、雨季、台風、日焼け対策）',
    '趣味（ムエタイ、音楽、映画、ゴルフ、SNS、ゲーム）',
    '学校（授業中、宿題、試験、放課後、語学学校）',
    '宗教・信仰（寺院マナー、托鉢、お守り、僧侶への話し方、仏教行事）',
    '伝統・祭り（ソンクラーン、ロイクラトン、王室行事、地域の伝統料理）',
    '礼儀作法（ワイの使い分け、敬語、タブー、食事マナー、贈り物）',
  ];

  // ---------------------------------------------------------------------------
  // ヒアリング（オンボーディングの4問）の goal → テーマ候補
  // ---------------------------------------------------------------------------

  /// ヒアリングで申告した用途（interview.goal）に対応するテーマ候補。
  /// テーマ未指定（おまかせ）のとき、ここから引いたテーマを明示指定として
  /// CF へ渡す。候補が複数あるものは生成のたびに引き直す（1テーマに固定すると
  /// 入門帯の旅行偏りを別のテーマに置き換えるだけになる）。
  ///
  /// 候補はヒアリング最終画面の文言（philosophy3Travel/Work/Live/Culture）が
  /// 名指ししているテーマを必ず含める。「『旅行』や『交通』が届きます」と
  /// 伝えた相手に別のテーマを出すと、その場で反故になる。学校・宗教・礼儀作法は
  /// どの文言でも触れていないので、語彙要求の高さを取って候補に入れない。
  ///
  /// 端末を経由しない毎日配信（deliverDailySentence）だけはサーバー側で同じ
  /// 対応表を使う（constants.py: INTERVIEW_GOAL_TOPICS）。並びを変えるときは
  /// 両方直すこと。
  static final interviewGoalTopics = <String, List<String>>{
    // 旅行・交通（+買い物/食べ物）
    'travel': [topics[5], topics[8], topics[7], topics[4]],
    // 仕事（+あいさつ）
    'work': [topics[2], topics[3]],
    // 買い物・家族（+健康/天気/交通/食べ物）
    'live': [topics[7], topics[6], topics[9], topics[10], topics[8], topics[4]],
    // タイBLドラマ・伝統・祭り（+趣味/恋愛）
    'culture': [topics[0], topics[14], topics[11], topics[1]],
  };

  /// [goal] に対応するテーマを1つ引く。未回答・未知の goal では null を返し、
  /// サーバーの自動選出（key_word 起点）に任せる。
  static String? topicForInterviewGoal(String? goal) {
    final candidates = interviewGoalTopics[goal];
    if (candidates == null || candidates.isEmpty) return null;
    return candidates[_random.nextInt(candidates.length)];
  }

  static final _random = Random();

  // ---------------------------------------------------------------------------
  // 丁寧さレベルの選択肢
  // ---------------------------------------------------------------------------

  /// 例文の丁寧さレベル一覧。
  /// タイ語の敬語・カジュアル表現の度合いを指定する。
  static const politenessLevels = [
    'フォーマル（丁寧語・敬語を使用）',
    'カジュアル（くだけた友達同士の表現）',
    '中立（一般的な日常表現）',
  ];

  // ---------------------------------------------------------------------------
  // 文法フォーカスの選択肢
  // ---------------------------------------------------------------------------

  /// 例文で重点的に使用する文法パターンの一覧。
  /// 括弧内にタイ語の具体例を含み、学習者がどの文法を練習できるか分かりやすくしている。
  static const grammarFocuses = [
    '疑問文（〜ไหม？〜มั้ย？など）',
    '否定文（ไม่〜、ไม่ได้〜など）',
    '条件文（ถ้า〜、หาก〜など）',
    '比較表現（กว่า、เหมือนなど）',
    '命令・依頼（〜นะ、〜ด้วยなど）',
    '可能表現（ได้、เป็นなど）',
    '過去・完了（แล้ว、เคยなど）',
    '助詞・接続詞（แต่、และ、หรือなど）',
  ];

  // ---------------------------------------------------------------------------
  // 感情・トーンの選択肢
  // ---------------------------------------------------------------------------

  /// 例文に含める感情・トーンの一覧。
  /// 感情表現の学習に役立てるため、さまざまな感情パターンを用意している。
  static const emotions = [
    '喜び・嬉しさ',
    '悲しみ・落ち込み',
    '驚き',
    '不安・心配',
    '期待・楽しみ',
    '中立・平静',
  ];

  // ---------------------------------------------------------------------------
  // 無料ティア / プレミアムティアの制限設定
  // ---------------------------------------------------------------------------

  /// 無料ティアで選択可能なスタイル。
  /// styles配列のインデックス 1（口語体）、2（丁寧語）に制限。
  static final freeStyles = [styles[1], styles[2]];

  // ---------------------------------------------------------------------------
  // パラメータ定義のメタ情報
  // ---------------------------------------------------------------------------

  /// パラメータキーとUI表示用ラベルのマッピング。
  /// 設定画面でパラメータ名を日本語で表示するために使用する。
  static const parameterLabels = {
    'style': 'スタイル',
    'topic': 'テーマ',
    'politeness': '丁寧さ',
    'grammarFocus': '文法フォーカス',
    'emotion': '感情・トーン',
  };

  /// パラメータキーと対応する選択肢リストのマッピング。
  /// パラメータキーから動的に選択肢リストを取得するために使用する。
  static const parameterOptions = {
    'style': styles,
    'topic': topics,
    'politeness': politenessLevels,
    'grammarFocus': grammarFocuses,
    'emotion': emotions,
  };
}
