// =============================================================================
// generation_constants.dart
// Gemini AIによるタイ語例文生成時に使用するパラメータの選択肢を定義する定数クラス。
//
// ユーザーは例文生成時にスタイル（口語体・丁寧語など）、トピック（あいさつ・食べ物など）、
// 文法フォーカス、語彙レベル、文の長さ、感情、学習目的、声調密度などのパラメータを
// 選択できる。これらの選択肢がCloud Functionに送信され、Gemini AIへのプロンプトに
// 組み込まれることで、ユーザーの学習ニーズに合った例文が生成される。
//
// 無料ティアとプレミアムティアで使用可能なパラメータ・選択肢が異なり、
// 無料ユーザーはトピックとスタイルの一部のみ選択可能。プレミアムユーザーは
// 全パラメータ・全選択肢にアクセスでき、さらに自由入力プロンプトも使用可能。
// =============================================================================

/// 例文生成パラメータの選択肢を定義する定数クラス。
///
/// 各パラメータ（スタイル、トピック、丁寧さ等）の選択肢リストと、
/// 無料/プレミアムティアでの利用可能範囲を管理する。
class GenerationConstants {
  /// インスタンス化を禁止するプライベートコンストラクタ
  GenerationConstants._();

  // ---------------------------------------------------------------------------
  // 例文スタイル（文体）の選択肢
  // ---------------------------------------------------------------------------

  /// 例文の文体スタイル一覧。
  /// 生成される例文がどのような文体で書かれるかを指定する。
  static const styles = [
    'ニュース記事体（客観的・フォーマルな報道文体）',
    '口語体（友達同士のカジュアルな話し言葉）',
    '丁寧語（フォーマルな敬語・丁寧な表現）',
    'SNS・テキストメッセージ（略語・絵文字・短い表現）',
    '物語・文学体（描写的・書き言葉的な表現）',
  ];

  // ---------------------------------------------------------------------------
  // トピック（話題）の選択肢
  // ---------------------------------------------------------------------------

  /// 例文のトピック一覧。
  /// どのような場面・話題の例文を生成するかを指定する。
  /// タイの文化・宗教・恋愛など、タイ語学習に実用的なトピックを網羅している。
  static const topics = [
    'あいさつ（朝、昼、夜のあいさつ、初対面、久しぶりの再会など）',
    '食べ物（レストランでの注文、料理の感想、食材の購入など）',
    '旅行（ホテル予約、道案内、観光地での会話など）',
    '感情（喜び、悲しみ、驚き、不安などの表現）',
    '仕事（職場での会話、ビジネスマナー、打ち合わせなど）',
    '家族（家族の紹介、日常会話、家族行事など）',
    '買い物（値段交渉、商品の質問、支払いなど）',
    '交通（タクシー、電車、バスでの会話）',
    '健康（病院、薬局、体調不良の説明など）',
    '天気（天気の話題、季節の挨拶など）',
    '趣味（スポーツ、音楽、映画などの趣味について）',
    '学校（授業、宿題、学校生活について）',
    '宗教・信仰（寺院訪問、お参り、托鉢、僧侶との会話、仏教行事など）',
    '伝統・祭り（ソンクラーン、ロイクラトン、王室行事、伝統儀式など）',
    '礼儀作法（ワイ（合掌）、年長者への敬意、タブー、社会的マナーなど）',
    '恋愛・男女関係（告白、デート、口説き文句、恋人同士の会話、別れなど）',
  ];

  // ---------------------------------------------------------------------------
  // 丁寧さレベルの選択肢
  // ---------------------------------------------------------------------------

  /// 例文の丁寧さレベル一覧。
  /// タイ語の敬語・カジュアル表現の度合いを指定する。
  static const politenessLevels = [
    'フォーマル（丁寧語・敬語を使用）',
    'カジュアル（くだけた友達同士の表現）',
    '中立（一般的な日常表現）',
  ];

  // ---------------------------------------------------------------------------
  // 文法フォーカスの選択肢
  // ---------------------------------------------------------------------------

  /// 例文で重点的に使用する文法パターンの一覧。
  /// 括弧内にタイ語の具体例を含み、学習者がどの文法を練習できるか分かりやすくしている。
  static const grammarFocuses = [
    '疑問文（〜ไหม？〜มั้ย？など）',
    '否定文（ไม่〜、ไม่ได้〜など）',
    '条件文（ถ้า〜、หาก〜など）',
    '比較表現（กว่า、เหมือนなど）',
    '命令・依頼（〜นะ、〜ด้วยなど）',
    '可能表現（ได้、เป็นなど）',
    '過去・完了（แล้ว、เคยなど）',
    '助詞・接続詞（แต่、และ、หรือなど）',
  ];

  // ---------------------------------------------------------------------------
  // 語彙レベルの選択肢
  // ---------------------------------------------------------------------------

  /// 例文で使用する語彙の難易度レベル一覧。
  /// 学習者のレベルに合わせた例文生成を可能にする。
  static const vocabLevels = [
    '初級（基本的な日常語彙のみ）',
    '中級（日常会話レベルの語彙）',
    '上級（やや専門的・慣用的な語彙）',
  ];

  // ---------------------------------------------------------------------------
  // 文の長さの選択肢
  // ---------------------------------------------------------------------------

  /// 生成する例文の長さ（単語数）の目安一覧。
  static const sentenceLengths = [
    '短文（5〜8単語）',
    '中文（9〜12単語）',
    '長文（13〜18単語）',
  ];

  // ---------------------------------------------------------------------------
  // 感情・トーンの選択肢
  // ---------------------------------------------------------------------------

  /// 例文に含める感情・トーンの一覧。
  /// 感情表現の学習に役立てるため、さまざまな感情パターンを用意している。
  static const emotions = [
    '喜び・嬉しさ',
    '悲しみ・落ち込み',
    '驚き',
    '不安・心配',
    '感謝',
    '期待・楽しみ',
    '中立・平静',
  ];

  // ---------------------------------------------------------------------------
  // 学習目的の選択肢
  // ---------------------------------------------------------------------------

  /// 学習の目的に応じた例文生成の方向性一覧。
  static const learningPurposes = [
    '会話練習（実際に話せる表現の習得）',
    '語彙習得（新しい単語の導入）',
    '文法理解（文法パターンの習得）',
    '文化理解（タイ文化・習慣の学習）',
  ];

  // ---------------------------------------------------------------------------
  // 声調密度の選択肢
  // ---------------------------------------------------------------------------

  /// 例文中に含まれる声調のバリエーション密度の一覧。
  /// タイ語は5種類の声調（平声・低声・下降声・高声・上昇声）を持ち、
  /// 声調練習を重視するユーザーには「高」密度の例文が適している。
  static const toneDensities = [
    '低（同じ声調が多め・声調バリエーション少なめ）',
    '中（複数の声調をバランスよく含む）',
    '高（5種類の声調をまんべんなく含む・声調練習向け）',
  ];

  // ---------------------------------------------------------------------------
  // 無料ティア / プレミアムティアの制限設定
  // ---------------------------------------------------------------------------

  /// 無料ティアで選択可能なトピック。
  /// topics配列のインデックス 0（あいさつ）、1（食べ物）、2（旅行）、6（買い物）に制限。
  static final freeTopics = [topics[0], topics[1], topics[2], topics[6]];

  /// 無料ティアで選択可能なスタイル。
  /// styles配列のインデックス 1（口語体）、2（丁寧語）に制限。
  static final freeStyles = [styles[1], styles[2]];

  /// 無料ティアで使用可能なパラメータキーのセット。
  /// 無料ユーザーはスタイルとトピックのみ選択可能。
  static const freeParameterKeys = {'style', 'topic'};

  /// プレミアム専用パラメータキーのセット。
  /// これらのパラメータはプレミアムサブスクリプション加入者のみ利用可能。
  static const premiumOnlyParameterKeys = {
    'politeness', 'grammarFocus', 'vocabLevel', 'sentenceLength',
    'emotion', 'learningPurpose', 'toneDensity',
  };

  // ---------------------------------------------------------------------------
  // 自由入力プロンプト設定
  // ---------------------------------------------------------------------------

  /// 自由入力パラメータのキー名。
  /// プレミアムユーザーが任意のテキストで例文の方向性を指定できる機能。
  static const customPromptKey = 'customPrompt';

  /// 自由入力プロンプトの最大文字数制限
  static const customPromptMaxLength = 20;

  // ---------------------------------------------------------------------------
  // パラメータ定義のメタ情報
  // ---------------------------------------------------------------------------

  /// パラメータキーとUI表示用ラベルのマッピング。
  /// 設定画面でパラメータ名を日本語で表示するために使用する。
  static const parameterLabels = {
    'style': 'スタイル',
    'topic': 'トピック',
    'politeness': '丁寧さ',
    'grammarFocus': '文法フォーカス',
    'vocabLevel': '語彙レベル',
    'sentenceLength': '文の長さ',
    'emotion': '感情・トーン',
    'learningPurpose': '学習目的',
    'toneDensity': '声調密度',
  };

  /// パラメータキーと対応する選択肢リストのマッピング。
  /// パラメータキーから動的に選択肢リストを取得するために使用する。
  static const parameterOptions = {
    'style': styles,
    'topic': topics,
    'politeness': politenessLevels,
    'grammarFocus': grammarFocuses,
    'vocabLevel': vocabLevels,
    'sentenceLength': sentenceLengths,
    'emotion': emotions,
    'learningPurpose': learningPurposes,
    'toneDensity': toneDensities,
  };
}
