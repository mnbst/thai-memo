"""テーマのショット（internal/themeshots）に「時点が要るか」「関係が要るか」を Gemini Decisions で付ける。

入力はショットの JSON 配列（id・scene・situation・text）。結果は JSONL に1行ずつ追記し、
再実行時は済んだ ID を飛ばす。time_data.go は --gen で JSONL から作る。

usage: GEMINI_API_KEY=... python3 scripts/label_shot_needs.py <shots.json> scripts/corpus/shot_needs.jsonl
       python3 scripts/label_shot_needs.py --gen scripts/corpus/shot_needs.jsonl functions/go/internal/themeshots/time_data.go
"""
import json, os, subprocess, sys, threading, time
from concurrent.futures import ThreadPoolExecutor

ENDPOINT = "https://generativelanguage.googleapis.com/v1beta/decisions"
Q = {
    "time": "Does `text` describe an event or situation located at a specific time, so that it is "
            "about something happening right now, that just happened, that will happen, a habit, or "
            "something in the past? Answer no for requests, invitations, questions about preferences, "
            "opinions or evaluations, greetings, thanks, and general facts or definitions that hold "
            "regardless of time.",
    "listener": "Is `text` addressed to one specific listener in a face-to-face or personal exchange, "
                "so that its pronouns, sentence-final particles, and politeness would change with the "
                "speaker's relationship to that listener? Answer no for narration, news, guidebook, "
                "encyclopedia, or notice-style text aimed at an unspecified reader.",
}
QUESTIONS = {k: {"type": "noul", "instructions":
    "The input is one Thai sentence (`text`) and, if known, the scene it comes from. " + q}
    for k, q in Q.items()}
lock = threading.Lock()

def ask(key, shot, f):
    inp = {"text": shot["text"], "scene": shot["situation"] or shot["scene"]}
    body = json.dumps({"model": "gemini-decision-1",
        "input": [{"type": "text", "text": json.dumps(inp, ensure_ascii=False)}],
        "questions": QUESTIONS}).encode()
    for a in range(6):
        try:
            r = subprocess.run(["curl", "-sS", "--fail-with-body", "-m", "60", ENDPOINT,
                "-H", "x-goog-api-key: " + key, "-H", "Content-Type: application/json",
                "--data-binary", "@-"], input=body, capture_output=True, check=True)
            ans = json.loads(r.stdout)["answers"]
            row = {"id": shot["id"], "time": round(ans["time"]["noul"], 3),
                   "listener": round(ans["listener"]["noul"], 3)}
            with lock:
                f.write(json.dumps(row) + "\n"); f.flush()
            return True
        except Exception as e:  # noqa: BLE001
            if a == 5:
                print("fail", shot["id"], e, file=sys.stderr); return False
            time.sleep(2 ** a)

# timeThreshold 未満のショットを「時点が要らない」とする。
TIME_THRESHOLD = 0.5


def gen(src, dst):
    ids = sorted(json.loads(l)["id"] for l in open(src) if l.strip()
                 and not json.loads(l)["id"].startswith("written_")
                 and json.loads(l)["time"] < TIME_THRESHOLD)
    with open(dst, "w") as f:
        f.write("// Code generated by scripts/label_shot_needs.py --gen. DO NOT EDIT by hand.\n\n")
        f.write("package themeshots\n\n")
        f.write("// shotNoTime は時点の要らないショット（依頼・質問・感想・あいさつ等）。Gemini Decisions で\n")
        f.write("// 「特定の時点の出来事・状況を述べる文か」を聞き、0.5 未満のもの（2026-11-21、会話 22794文中 12416文）。\n")
        f.write("var shotNoTime = map[string]bool{\n")
        for i in ids:
            f.write(f"\t{json.dumps(i)}: true,\n")
        f.write("}\n")


if sys.argv[1] == "--gen":
    gen(sys.argv[2], sys.argv[3])
    sys.exit(0)

key = os.environ["GEMINI_API_KEY"]
shots = json.load(open(sys.argv[1]))
done = set()
if os.path.exists(sys.argv[2]):
    done = {json.loads(l)["id"] for l in open(sys.argv[2]) if l.strip()}
todo = [s for s in shots if s["id"] not in done]
print(f"todo {len(todo)} / {len(shots)}", file=sys.stderr, flush=True)
with open(sys.argv[2], "a") as f, ThreadPoolExecutor(16) as ex:
    ok = sum(ex.map(lambda s: ask(key, s, f), todo))
print(f"ok {ok} / {len(todo)}", file=sys.stderr)
